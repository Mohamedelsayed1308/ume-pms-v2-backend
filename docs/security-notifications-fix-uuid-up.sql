--  ما جرى
--  ------
--  كُتب العمودان `id uuid PRIMARY KEY` بلا `DEFAULT`، خلافاً لاتّفاقيّة المشروع
--  في كلّ هجرةٍ سابقة. وTypeORM مع Postgres يُرسل `DEFAULT` لعمود المفتاح
--  المولَّد ويترك القاعدة تولّده — فبلا افتراضٍ يفشل الإدخال بخطأ `NOT NULL`.
--
--  والأثر: الدخول من جهازٍ آخر كان يُبطل الجلسة القديمة ويُظهر رسالة الخروج
--  (فذلك لا يمرّ بالجدولين)، ثمّ يسقط تسجيل الحادثة بصمتٍ داخل `try/catch`
--  فلا حادثةَ ولا إشعارَ لأحد.
--
--  الأمان
--  ------
--  تعديلُ افتراضٍ فحسب: لا عمودَ يُضاف أو يُحذف، ولا صفَّ يُقرأ أو يُكتب.
--  ومتكرّرة الأمان: `SET DEFAULT` على القيمة نفسها لا يُغيّر شيئاً.
--
--  التشغيل:  docs/security-notifications-fix-uuid-up.sql
-- ============================================================================

BEGIN;

ALTER TABLE security_events ALTER COLUMN id SET DEFAULT gen_random_uuid();
ALTER TABLE notifications   ALTER COLUMN id SET DEFAULT gen_random_uuid();

COMMIT;
