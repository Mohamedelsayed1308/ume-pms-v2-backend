-- P1.1A.1 · تصحيح دلالات الفترة الافتتاحية
--
-- تصحيح **إعداد** لا هجرة: صفَّان في جداول الإعداد. صفر تغيير في المخطط ·
-- صفر مساس ببيانات أعمال · صفر قيد محاسبي (لا توجد قيود أصلاً).
--
-- ما يُصحَّح:
--   1. legal_entities.accounting_start_date : 2025-12-31 → 2026-01-01
--   2. الفترة 0 لـFY2026                    : 2025-12-31 → 2026-01-01
--
-- لماذا: 31/12/2025 هو **تاريخ مصدر الرصيد** (إقفال السنة السابقة) لا فترة
-- تابعة لـFY2026. والرصيد المُرحَّل يُثبَت بأثر 01/01/2026 داخل السنة نفسها.
-- تقديم بداية المحاسبة إلى 2025 كان علاجاً لعَرَض بإضعاف الحدّ نفسه.
--
-- ⚠️ حارس: يرفض التنفيذ إن وُجد أي قيد — عندها لا يعود تصحيحاً بل ترحيل بيانات.
-- ═══════════════════════════════════════════════════════════════════════════

BEGIN;

DO $$
DECLARE n INT;
BEGIN
  SELECT count(*) INTO n FROM journal_entries;
  IF n > 0 THEN
    RAISE EXCEPTION
      'يوجد % قيد محاسبي — هذا التصحيح مخصَّص لحالة الدفاتر الفارغة وحدها. توقّف.', n;
  END IF;
END $$;

-- 1 · بداية المحاسبة = أول يوم في السنة المالية
UPDATE legal_entities
   SET accounting_start_date = DATE '2026-01-01',
       updated_at = now()
 WHERE code = 'SIV'
   AND accounting_start_date = DATE '2025-12-31';

-- 2 · الفترة الافتتاحية تنتقل داخل السنة المالية
UPDATE fiscal_periods p
   SET start_date = DATE '2026-01-01',
       end_date   = DATE '2026-01-01'
  FROM fiscal_years fy
 WHERE p.fiscal_year_id = fy.id
   AND fy.year = 2026
   AND p.period_no = 0
   AND p.start_date = DATE '2025-12-31';

COMMIT;
