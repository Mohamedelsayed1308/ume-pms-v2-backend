import { Entity, PrimaryColumn, Column } from 'typeorm';

/**
 * ═══════════════════════════════════════════════════════════════════════════
 * رمز بند المصروف في هيكل التكاليف — بأمر المالك ٢٩ سبتمبر ٢٠٢٦
 *
 * هيكل التكاليف في تقارير المركب ستّ مجموعات، لكلٍّ حرف:
 *   A عمولات الوكلاء · B البنكر المستهلك · C المشتريات والخدمات
 *   D ميناء ومناولة · E تكاليف تشغيل ثابتة (المرتّبات) · F أخرى
 *
 * وثلاثٌ منها (B · C · E) سطورٌ تُؤخَذ من قائمة الدخل نصّاً بقرار ١٧ سبتمبر،
 * فلا يُحفظ لها ربط. وما يُحفظ هنا هو بنود سطر «مصروفات الوكلاء» وحدها — مفاتيح
 * دفتر المركب (`broker`، `egyPort`، …) — وكلٌّ منها يذهب إلى A أو D أو F.
 *
 * الجدول للأسطول كلّه: المفتاح نفسه في دفترَي ألكوديا وبيلاجوس له المعنى نفسه.
 * والبند الغائب عن الجدول يأخذ تصنيفه الافتراضيّ من الواجهة؛ فحذف الصفّ رجوعٌ
 * إلى الافتراضيّ لا فقدٌ لشيء.
 * ═══════════════════════════════════════════════════════════════════════════
 */
@Entity('cost_item_codes')
export class CostItemCode {
  @PrimaryColumn({ type: 'varchar', length: 60 }) item_key: string;

  @Column({ type: 'char', length: 1 }) code: string;

  @Column({ type: 'varchar', length: 120, default: '' }) updated_by: string;

  @Column({ type: 'timestamptz', default: () => 'now()' }) updated_at: Date;
}
