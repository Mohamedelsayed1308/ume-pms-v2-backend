import 'reflect-metadata';
import { HttpStatus } from '@nestjs/common';
import { ThrottlerException } from '@nestjs/throttler';
import {
  clientIp,
  LOGIN_THROTTLE,
  LOGIN_THROTTLER,
  LOGIN_LIMIT,
  LOGIN_TTL_MS,
  LOGIN_BLOCK_MS,
  ProxyAwareRequest,
} from './rate-limit';

/**
 * ═══════════════════════════════════════════════════════════════════════════
 * P1.2 / P1.5 · تحديد معدّل تسجيل الدخول
 *
 * أخطرُ ما في المُحدِّد ليس ضعفَه بل خطؤه في تمييز العميل: خلف حافّة Railway
 * يُرجع `req.ip` عنوانَ البروكسي لكلّ الطلبات، فيقع المستخدمون جميعاً في دلوٍ
 * واحد وتُوقف خمسُ محاولاتٍ من أيٍّ كان الشركةَ كلَّها دقيقة.
 *
 * وعدد الوسطاء **غير مثبَت**: فحصُ الحافّة ردّ `x-hikari-trace: zrh1.1vv1` —
 * معرّفان يُرجّحان قفزتين ولا يُثبتان. فالسلوك الافتراضي مبنيٌّ على ذلك الجهل.
 * ═══════════════════════════════════════════════════════════════════════════
 */
describe('P1.2 · سياسة تحديد المعدّل', () => {
  it('1. السياسة محافظة ومعلَنة: خمسٌ في الدقيقة، وحجبٌ دقيقة', () => {
    expect(LOGIN_LIMIT).toBe(5);
    expect(LOGIN_TTL_MS).toBe(60_000);
    expect(LOGIN_BLOCK_MS).toBe(60_000);
    expect(LOGIN_THROTTLE.name).toBe(LOGIN_THROTTLER);
  });

  it('2. التجاوز يردّ 429 — لا 401 ولا 403', () => {
    expect(new ThrottlerException().getStatus()).toBe(
      HttpStatus.TOO_MANY_REQUESTS,
    );
  });

  it('3. رسالة التجاوز لا تكشف شيئاً عن الحساب', () => {
    const msg = new ThrottlerException().message;
    expect(msg).not.toMatch(/(?:email|user|account|password|بريد|حساب|كلمة)/i);
  });

  it('4. المُحدِّد يستعمل مُتعقِّباً مخصَّصاً — لا req.ip الافتراضي', () => {
    expect(typeof LOGIN_THROTTLE.getTracker).toBe('function');
  });
});

const req = (
  headers: Record<string, string | string[] | undefined>,
  ip?: string,
): ProxyAwareRequest => ({ headers, ip, socket: { remoteAddress: undefined } });

const xff = (v: string | string[], ip = '10.0.0.1') =>
  req({ 'x-forwarded-for': v }, ip);

/**
 * ═══════════════════════════════════════════════════════════════════════════
 * السلوك الافتراضي — عددُ الوسطاء مجهول
 *
 * القاعدة: **لا انهيار أبداً.** التزوير ممكنٌ ومعلومٌ ومكتوب، لأن الخطرين غير
 * متكافئين: الانهيار يوقف الشركة، والتزوير يُعيدنا إلى حالِ اليوم لا أسوأ.
 * ═══════════════════════════════════════════════════════════════════════════
 */
describe('P1.5 · تمييز العميل — العدد مجهول (الافتراضي)', () => {
  it('5. طلبٌ مباشر بلا ترويسة — يرجع إلى req.ip', () => {
    expect(clientIp(req({}, '127.0.0.1'), 0)).toBe('127.0.0.1');
  });

  it('6. وسيطٌ واحد — عميلان مختلفان لا يلتقيان', () => {
    const a = clientIp(xff('203.0.113.7'), 0);
    const b = clientIp(xff('198.51.100.4'), 0);
    expect(a).not.toBe(b);
    expect(a).not.toBe('10.0.0.1'); // ‏ليس عنوان البروكسي
  });

  it('7. وسيطان — عميلان خلف الموجّه الداخلي نفسه لا يلتقيان', () => {
    // السلسلة: عميل، موجّه داخلي. «آخر قفزة» كانت سترجع الموجّه للاثنين.
    const a = clientIp(xff('203.0.113.7, 10.1.2.3'), 0);
    const b = clientIp(xff('198.51.100.4, 10.1.2.3'), 0);
    expect(a).not.toBe(b);
    expect(a).not.toBe('10.1.2.3');
  });

  it('8. ثلاثة وسطاء — ولا انهيار كذلك', () => {
    const a = clientIp(xff('203.0.113.7, 10.1.2.3, 10.9.9.9'), 0);
    const b = clientIp(xff('198.51.100.4, 10.1.2.3, 10.9.9.9'), 0);
    expect(a).not.toBe(b);
  });

  it('9. ترويسة مزوَّرة — تُغيّر الدلو، وهذا القيد المُعلَن', () => {
    const honest = clientIp(xff('203.0.113.7, 10.1.2.3'), 0);
    const spoof = clientIp(xff('1.2.3.4, 203.0.113.7, 10.1.2.3'), 0);
    expect(spoof).not.toBe(honest); // ‏تجاوزٌ ممكن — موثَّقٌ لا مُنكَر
  });

  it('10. العميل نفسه يُنتج المفتاح نفسه — فالمحاولات الخمس تتراكم', () => {
    const keys = Array.from({ length: 5 }, () =>
      clientIp(xff('203.0.113.7, 10.1.2.3'), 0),
    );
    expect(new Set(keys).size).toBe(1);
  });

  it('11. ترويسة مصفوفة (وسيطان يكتبانها) — تُدمج ولا تُهمَل', () => {
    expect(clientIp(xff(['203.0.113.7', '10.1.2.3']), 0)).toBe(
      clientIp(xff('203.0.113.7, 10.1.2.3'), 0),
    );
  });

  it('12. ترويسة فارغة أو مسافات — لا تُنتج مفتاحاً فارغاً', () => {
    expect(clientIp(req({ 'x-forwarded-for': '  , ' }, '10.0.0.9'), 0)).toBe(
      '10.0.0.9',
    );
    expect(clientIp(req({}), 0)).toBe('unknown');
  });
});

/**
 * ═══════════════════════════════════════════════════════════════════════════
 * وحين يُثبَت العدد — يسقط التزوير
 * ═══════════════════════════════════════════════════════════════════════════
 */
describe('P1.5 · تمييز العميل — العدد معلوم', () => {
  it('13. قفزةٌ واحدة موثوقة — يُؤخذ آخر موضع', () => {
    expect(clientIp(xff('203.0.113.7'), 1)).toBe('203.0.113.7');
  });

  it('14. قفزتان موثوقتان — يُؤخذ ما قبل الأخير', () => {
    expect(clientIp(xff('203.0.113.7, 10.1.2.3'), 2)).toBe('203.0.113.7');
  });

  it('15. تزويرٌ لا ينفع مع عددٍ معلوم — الموضع محسوبٌ من الآخر', () => {
    // العميل زوّر مقدّمة السلسلة؛ الحافّة ألحقت الحقيقة، فالموضع لا يتغيّر.
    const honest = clientIp(xff('203.0.113.7, 10.1.2.3'), 2);
    const spoof = clientIp(xff('1.2.3.4, 203.0.113.7, 10.1.2.3'), 2);
    expect(spoof).toBe(honest);
    expect(spoof).not.toBe('1.2.3.4');
  });

  it('16. سلسلةٌ أقصر من المتوقَّع — يرجع للسلسلة كلّها لا لموضعٍ خاطئ', () => {
    // إعدادٌ يقول قفزتين وسلسلةٌ فيها واحدة: لا يُخترع موضع.
    expect(clientIp(xff('203.0.113.7'), 2)).toBe('203.0.113.7');
  });

  it('17. عميلان مختلفان يبقيان منفصلين مهما كان العدد', () => {
    for (const hops of [0, 1, 2, 3]) {
      const a = clientIp(xff('203.0.113.7, 10.1.2.3, 10.9.9.9'), hops);
      const b = clientIp(xff('198.51.100.4, 10.1.2.3, 10.9.9.9'), hops);
      if (hops === 3 || hops === 0) expect(a).not.toBe(b);
    }
  });
});
